import { createClient, type SupabaseClient } from "@supabase/supabase-js";

export const DSE_NEWS_BUCKET = "dse-news-media";
export const MAX_MAIN_BYTES = 2_621_440; // 2.5 MB
export const MAX_THUMB_BYTES = 245_760; // 240 KB
export const MAX_PACKET_BYTES = 4 * 1024 * 1024;

export class NewsMediaError extends Error {
  constructor(public status: number, message: string) { super(message); }
}

let client: SupabaseClient | null = null;

/** Storage is always private and only the backend can use the service role. */
export function newsMediaStorage(): SupabaseClient {
  // The Neon staging database is intentionally isolated from production Supabase
  // Storage. Never let a staging user write to a production storage project.
  if (process.env.AUTH_MODE === "neon-staging" || process.env.DSE_NEWS_STORAGE_DISABLED === "true") {
    throw new NewsMediaError(503, "Photo uploads require a dedicated private storage environment");
  }
  if (client) return client;
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new NewsMediaError(503, "Private news photo storage is not configured");
  client = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  return client;
}

export type CompressedPhotoPack = {
  main: Uint8Array;
  thumbnail: Uint8Array;
  width: number;
  height: number;
};

function bytes(text: string): Uint8Array { return new TextEncoder().encode(text); }
const RIFF = bytes("RIFF"), WEBP = bytes("WEBP");

/** This format is generated by the browser canvas; it never contains the original EXIF metadata. */
export function dimensionsOfWebp(data: Uint8Array): { width: number; height: number } {
  if (data.length < 30 || !RIFF.every((v,i)=>data[i]===v) || !WEBP.every((v,i)=>data[i+8]===v)) {
    throw new NewsMediaError(400, "Compressed image must be a valid WebP file");
  }
  const view = new DataView(data.buffer, data.byteOffset, data.byteLength);
  if (view.getUint32(4,true) + 8 !== data.length) {
    throw new NewsMediaError(400, "Incomplete or invalid WebP file length");
  }
  const chunk = String.fromCharCode(...data.slice(12,16));
  let width = 0, height = 0;
  if (chunk === "VP8X") {
    if ((data[20]! & 0x02) !== 0) throw new NewsMediaError(400, "Animated images are not supported");
    width = 1 + data[24]! + (data[25]! << 8) + (data[26]! << 16);
    height = 1 + data[27]! + (data[28]! << 8) + (data[29]! << 16);
  } else if (chunk === "VP8L") {
    if (data.length < 25 || data[20] !== 0x2f) throw new NewsMediaError(400, "Invalid lossless WebP");
    width = 1 + (data[21]! | ((data[22]! & 0x3f) << 8));
    height = 1 + ((data[22]! >> 6) | (data[23]! << 2) | ((data[24]! & 0x0f) << 10));
  } else if (chunk === "VP8 ") {
    if (data.length < 30 || data[23] !== 0x9d || data[24] !== 0x01 || data[25] !== 0x2a) {
      throw new NewsMediaError(400, "Invalid lossy WebP");
    }
    width = view.getUint16(26, true) & 0x3fff;
    height = view.getUint16(28, true) & 0x3fff;
  } else {
    throw new NewsMediaError(400, "Unsupported WebP encoding");
  }
  if (!width || !height) throw new NewsMediaError(400, "Image dimensions are invalid");
  return {width,height};
}

/**
 * 8-byte little-endian header: main byte length, thumbnail byte length,
 * followed by the two WebP files. Enforce both sizes and image signatures
 * even when a caller bypasses browser-side compression.
 */
export function parseCompressedPhotoPack(input: Uint8Array): CompressedPhotoPack {
  if (input.length < 68 || input.length > MAX_PACKET_BYTES) throw new NewsMediaError(400,"Image upload is empty or too large");
  const view = new DataView(input.buffer, input.byteOffset, input.byteLength);
  const mainLength = view.getUint32(0,true), thumbnailLength = view.getUint32(4,true);
  if (mainLength < 30 || mainLength > MAX_MAIN_BYTES ||
      thumbnailLength < 30 || thumbnailLength > MAX_THUMB_BYTES ||
      mainLength + thumbnailLength + 8 !== input.length) {
    throw new NewsMediaError(400,"Invalid compressed image packet or image size");
  }
  const main=input.slice(8,8+mainLength),thumbnail=input.slice(8+mainLength);
  const {width,height}=dimensionsOfWebp(main);
  const small=dimensionsOfWebp(thumbnail);
  if (width>2000 || height>2000 || small.width>480 || small.height>480 ||
      small.width>width || small.height>height) {
    throw new NewsMediaError(400,"Image or thumbnail dimensions exceed the allowed size");
  }
  return {main,thumbnail,width,height};
}

export function validateMediaMetadata(kind: unknown, alt: unknown): {kind:"cover"|"gallery";alt:string} {
  if (kind!=="cover" && kind!=="gallery") throw new NewsMediaError(400,"Choose cover or gallery");
  if (typeof alt!=="string" || alt.trim().length<3 || alt.trim().length>250) {
    throw new NewsMediaError(400,"Photo description must be between 3 and 250 characters");
  }
  return {kind,alt:alt.trim()};
}

export async function signedNewsMediaUrl(path: string): Promise<string> {
  const {data,error}=await newsMediaStorage().storage.from(DSE_NEWS_BUCKET).createSignedUrl(path, 900);
  if (error || !data?.signedUrl) throw new NewsMediaError(502,"Could not create a private photo preview");
  return data.signedUrl;
}
